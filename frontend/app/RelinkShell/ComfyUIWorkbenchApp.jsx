// ComfyUIWorkbenchApp — THE COMFY VIEWPORT: the operator's door to the
// supervised ComfyUI, inside the desk.
//
// Design note, 2026-08-01: […]
//
// So the window is two panes on ONE engine:
//   • the CANVAS — ComfyUI's own UI, embedded, where the operator works by hand
//   • the RAIL   — what the beings are doing, which the canvas CANNOT show
//
// Why the rail exists at all: ComfyUI routes a job's `executing`/`progress`/
// `executed` events to the submitting `client_id` ALONE (execution.py:732-735),
// and NEUMA's job lane holds that socket. An operator staring at the canvas
// while a being renders sees the queue counter tick and nothing else. The rail
// is the backend re-broadcasting what its own lane socket already receives.
//
// Why a <webview> and not an iframe: ComfyUI 403s any request carrying
// `Sec-Fetch-Site: cross-site` (server.py origin_only_middleware), which is
// every iframe load from the desk origin. A webview navigates its own top-level
// browsing context, so the document origin IS the engine's own — the property
// NFR-3 depends on. The guest carries no preload and no node, and the main
// process re-imposes that in `will-attach-webview`; the desk origin still never
// touches the engine API. Outside Electron there is no webview, so the card
// falls back to the detached window it has always used.

import { useEffect, useRef, useState } from 'react';
import { uiSound } from '../../services/ui-sound.js';
import {
  getForgeStatus, launchForge, stopForge, freeForge, getForgeActivity,
} from '../../services/image-forge-client.js';
import { deriveForgeCard, workbenchUrl, deriveActivityRail } from './comfyui-workbench-view.js';
import { AuthImage } from './AuthImage.jsx';
import { AppTitle } from './app-title.jsx';
import { useVisibleInterval } from './use-visible-interval.js';
import './ComfyUIWorkbenchApp.css';

const ForgeIcon = () => (
  <svg width="14" height="14" viewBox="0 0 16 16" fill="none" stroke="currentColor" strokeWidth="1.2" aria-hidden="true">
    <rect x="2" y="2" width="12" height="12" rx="1" />
    <circle cx="6" cy="6" r="1.6" />
    <path d="M2 11.5 L6.5 8.5 L9.5 10.5 L14 7.5" />
  </svg>
);

const POLL_MS = 2500;
// The rail is a progress bar someone is watching — it polls faster than the
// supervisor card, and only while the engine is actually up.
const ACTIVITY_POLL_MS = 700;

// impure — can this desk embed the engine? Electron only; the browser desk has
// no <webview> and an iframe is refused by the engine.
const canEmbed = () => typeof window !== 'undefined' && Boolean(window.neuma?.workbench?.open);

// impure — open ComfyUI's own UI top-level: Electron child window when the
// bridge offers it, else a new tab. The POP OUT lane, and the whole story on a
// browser desk.
const openTopLevel = (url) => {
  if (typeof window !== 'undefined' && window.neuma?.workbench?.open) {
    return window.neuma.workbench.open(url);
  }
  window.open(url, '_blank', 'noopener,noreferrer');
  return Promise.resolve({ opened: true });
};

// The embedded canvas. `partition` keeps the engine's cookies/storage in the
// same jar the detached window used, so a workbench layout survives either
// door. No preload, no nodeintegration — main enforces both regardless.
const Canvas = ({ url }) => (
  <webview
    className="forgebench-canvas"
    src={url}
    partition="persist:comfyui-workbench"
    allowpopups="false"
  />
);

const ActivityRow = ({ row }) => (
  <li className={`forgebench-row${row.live ? ' is-live' : ''}${row.bad ? ' is-bad' : ''}`}>
    <div className="forgebench-row-head">
      <span className="label-data forgebench-row-word">{row.word}</span>
      <span className="forgebench-row-who">{row.who}</span>
    </div>
    {row.pipeline ? <p className="forgebench-row-pipe">{row.pipeline}</p> : null}
    {row.percent !== null ? (
      <div className="forgebench-bar" role="progressbar" aria-valuenow={row.percent} aria-valuemin={0} aria-valuemax={100}>
        <span className="forgebench-bar-fill" style={{ width: `${row.percent}%` }} />
        <span className="forgebench-bar-num">{row.percent}%</span>
      </div>
    ) : null}
    {row.detail ? <p className="forgebench-row-detail">{row.detail}</p> : null}
    {row.images.length ? (
      <div className="forgebench-thumbs">
        {row.images.map((img) => (
          // The bytes are lane-scoped and auth-gated, so a bare <img src> can
          // only render broken — it sends no Bearer token and no laneId.
          <AuthImage
            key={img.imageId}
            className="forgebench-thumb"
            src={`${img.url}?laneId=${encodeURIComponent(row.laneId || '')}`}
            alt={`generated by ${row.who}`}
          />
        ))}
      </div>
    ) : null}
  </li>
);

const ActivityRail = ({ rail, engineUp }) => (
  <aside className="forgebench-rail">
    <div className="forgebench-rail-head">
      <span className="label-data">AI ACTIVITY</span>
      {rail.liveCount > 0 ? <span className="forgebench-rail-live">{rail.liveCount} LIVE</span> : null}
    </div>
    {rail.idle ? (
      <p className="forgebench-note">
        {engineUp
          ? 'Nothing rendering. When a being generates an image on this engine, it appears here — ComfyUI’s own canvas cannot show you its work.'
          : 'The engine is resting. Beings’ renders appear here once it is up.'}
      </p>
    ) : (
      <ul className="forgebench-rows">
        {rail.rows.map((row) => <ActivityRow key={row.jobId} row={row} />)}
      </ul>
    )}
  </aside>
);

const ComfyUIWorkbenchBody = () => {
  const [status, setStatus] = useState(null);
  const [activity, setActivity] = useState(null);
  const [error, setError] = useState(null);
  const [busy, setBusy] = useState(false);
  // The canvas mounts only after the operator opens it: a <webview> that loads
  // a dead port shows the guest's own network error, which reads as a NEUMA
  // fault. The card's own words are the honest surface until the engine is up.
  const [showCanvas, setShowCanvas] = useState(false);
  const alive = useRef(true);

  const refresh = async () => {
    try {
      const s = await getForgeStatus();
      if (!alive.current) return;
      setStatus(s);
      setError(null);
    } catch (e) {
      if (alive.current) setError(e.message);
    }
  };

  useEffect(() => {
    alive.current = true;
    return () => { alive.current = false; };
  }, []);
  // Both polls are gated on sight (use-visible-interval.js): a shaded or
  // hidden FORGE reads nothing, and reads at once when it is opened again.
  useVisibleInterval(refresh, POLL_MS);

  const engineUp = status?.state === 'ready';

  // The rail polls only while the engine is up — a resting engine has no
  // activity to report, and this window can sit open all day.
  useVisibleInterval(async () => {
    try {
      const a = await getForgeActivity();
      if (alive.current) setActivity(a);
    } catch { /* the card's own error line owns engine trouble */ }
  }, ACTIVITY_POLL_MS, { enabled: engineUp });

  const card = deriveForgeCard(status);
  const rail = deriveActivityRail(activity);

  // Bring the engine to READY, answering with the ready status. Shared by the
  // embedded open and POP OUT so neither can drift from the other.
  const ensureReady = async () => {
    let s = status;
    if (s?.state === 'ready') return s;
    s = await launchForge();
    setStatus(s);
    const deadline = Date.now() + 120_000;
    while (s.state !== 'ready' && Date.now() < deadline) {
      if (s.state === 'stopped' && s.lastError?.error) throw new Error(s.lastError.error);
      await new Promise((r) => setTimeout(r, 1000));
      s = await getForgeStatus();
      if (!alive.current) throw new Error('window closed');
      setStatus(s);
    }
    if (s.state !== 'ready') throw new Error(s.lastError?.error || 'engine did not become ready');
    return s;
  };

  const run = async (act) => {
    uiSound('toggle');
    setBusy(true);
    setError(null);
    try { await act(); } catch (e) { if (alive.current) setError(e.message); }
    if (alive.current) setBusy(false);
  };

  // OPEN: launch if needed, then show the canvas in THIS window.
  const onOpen = () => run(async () => {
    await ensureReady();
    if (canEmbed()) { setShowCanvas(true); return; }
    // Browser desk: no webview to embed into, so the old top-level door.
    await openTopLevel(workbenchUrl(status));
  });

  const onPopOut = () => run(async () => {
    const s = await ensureReady();
    await openTopLevel(workbenchUrl(s));
  });

  const onStop = () => run(async () => {
    setShowCanvas(false);
    setStatus(await stopForge());
  });

  const onFree = () => run(async () => { setStatus(await freeForge()); });

  const canvasLive = showCanvas && engineUp && canEmbed();

  return (
    <div className={`forgebench${canvasLive ? ' is-open' : ''}`}>
      <div className="forgebench-bar-top">
        <div className="forgebench-status" data-phase={card.phase}>
          <span className={`forgebench-lamp forgebench-lamp-${card.phase}`} aria-hidden="true" />
          <span className="label-data forgebench-word">{card.phase.replace('-', ' ').toUpperCase()}</span>
          <span className="forgebench-line">{card.line}</span>
        </div>

        {card.phase === 'not-installed' ? null : (
          <div className="forgebench-actions">
            {canvasLive ? null : (
              <button type="button" className="forgebench-act" disabled={!card.canOpen || busy} onClick={onOpen}>
                {busy ? 'WORKING…' : card.phase === 'failed' ? 'RETRY' : 'OPEN WORKBENCH'}
              </button>
            )}
            {canvasLive ? (
              <button type="button" className="forgebench-act" disabled={busy} onClick={onPopOut}>POP OUT</button>
            ) : null}
            {card.canStop ? (
              <>
                <button type="button" className="forgebench-act" disabled={busy} onClick={onFree}>FREE VRAM</button>
                <button type="button" className="forgebench-act" disabled={busy} onClick={onStop}>{card.stopWord}</button>
              </>
            ) : null}
          </div>
        )}
      </div>

      {card.phase === 'not-installed' ? (
        <p className="forgebench-note">
          Set COMFYUI_INSTALL_DIR to an existing install, or install from
          Settings once the managed install lane lands — the card wakes on its
          own when the engine is present.
        </p>
      ) : null}

      {error ? <p className="forgebench-err">{error}</p> : null}

      <div className="forgebench-panes">
        {canvasLive ? (
          <Canvas url={workbenchUrl(status)} />
        ) : (
          <p className="forgebench-note forgebench-idle">
            The full ComfyUI workbench on the NEUMA-managed engine — compose and
            render by hand while the rail beside you shows what the beings are
            doing on the same engine. NEUMA launches, supervises, and rests it
            around you.
          </p>
        )}
        <ActivityRail rail={rail} engineUp={engineUp} />
      </div>
    </div>
  );
};

export const comfyUIWorkbenchApp = {
  label: 'COMFY',
  labelKey: 'apps.comfyui',
  icon: <ForgeIcon />,
  title: <AppTitle label="COMFY" labelKey="apps.comfyui" />,
  Body: ComfyUIWorkbenchBody,
  storageKey: 'comfyui',
};
