/**
 * KOTODAMA NAME LEXICON — the real words given names are made from
 * (docs/work/naming-meaning.md): Latin, Ancient Greek, Sanskrit, Old Norse,
 * Old English, Welsh and Japanese.
 *
 * A given name is two elements joined, the old way names were built
 * (Wil-helm, Vladi-mir): an opener, then a closer. Every element is a real
 * word: its form in the name, its language, the word in its own script with
 * a romanization, and what it means in English.
 *
 * Row: [form, lang, source word, English gloss, how the gloss reads after
 * "of", kind, mark]. The kind says where a word may stand:
 *   n  a noun: opens a name or closes it ("Hoshi-wyn", "Kai-hoshi")
 *   a  an adjective: opens only, and reads before the closer ("golden lotus")
 *   e  an ending: closes a being's name only (joy, protector, lotus, bell)
 *   p  a place: closes a house's name only (home, valley, island)
 * The optional mark "water" keeps a name from saying water twice ([…]). Any noun may meet any other: […] stands.
 *
 * Choices this table holds to: no deity names or sacred terms; no gendered
 * name endings (a given name assigns no lean — the being declares its own);
 * forms are plain a-z, so a house name stays a safe folder segment.
 *
 * The rows are dictionary entries: the public export passes them whole even
 * where a word is also some being's name, so a public build makes the same
 * names.
 *
 * Changing a row changes no existing name: a minted name stores its parts.
 * Pure data.
 */

